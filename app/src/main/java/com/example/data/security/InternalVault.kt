    private fun decodeBytes(table: IntArray, salt: Int): ByteArray {
        val rot = (salt % 5) + 1
        val mask = masterMask
        val out = ByteArray(table.size)
        for (i in table.indices) {
            val r = table[i] and 0xFF
            val x = ((r ushr rot) or (r shl (8 - rot))) and 0xFF
            val k = ((mask[(i + salt) % mask.size].toInt() and 0xFF) xor ((i * 37 + salt * 13) and 0xFF)) and 0xFF
            out[i] = (x xor k).toByte()
        }
        return out
    }

    private fun unpackPlain(table: IntArray, salt: Int): String =
        String(decodeBytes(table, salt), StandardCharsets.UTF_8)

