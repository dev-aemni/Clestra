        val trimmed = rawInput.trim()
        if (trimmed.isEmpty()) return null
        val inputBytes = trimmed.toByteArray(StandardCharsets.UTF_8)
        val pepper = decodeBytes(pepperData, 101)
        val md = MessageDigest.getInstance("SHA-256")

        for (slot in tagSlots) {
            val initial = ByteArray(pepper.size + 1 + inputBytes.size + 1)
            System.arraycopy(pepper, 0, initial, 0, pepper.size)
            initial[pepper.size] = (slot.salt and 0xFF).toByte()
            System.arraycopy(inputBytes, 0, initial, pepper.size + 1, inputBytes.size)
            initial[initial.size - 1] = ((slot.salt * 7) and 0xFF).toByte()

            var cur = initial
            val stepBuf = ByteArray(33)
            for (round in 0 until 4096) {
                md.reset()
                if (round == 0) {
                    md.update(cur)
                } else {
                    System.arraycopy(cur, 0, stepBuf, 0, 32)
                    stepBuf[32] = (round and 0xFF).toByte()
                    md.update(stepBuf)
                    // round 0 uses initial + 0x00 below
                }
                if (round == 0) {
                    md.update(0.toByte())
                }
                cur = md.digest()
            }

            val expected = ByteArray(slot.hash.size) { idx -> slot.hash[idx].toByte() }
            if (MessageDigest.isEqual(cur, expected)) {
                return unpackPlain(slot.labelData, slot.salt)
            }
        }
        return null
    }
