    fun buildPrompt(userName: String, userId: String): String {
        val gz = decodeBytes(sysPromptData, 97)
        val template = GZIPInputStream(ByteArrayInputStream(gz)).use { stream ->
            String(stream.readBytes(), StandardCharsets.UTF_8)
        }
        return template
            .replace("{{UN}}", userName)
            .replace("{{UID}}", userId)
    }

    /**
     * Verifies a secret redeem code using 4096-round iterated salted SHA-256.
     * No plaintext redeem code exists anywhere in the APK.
     */
